"""Shared, test-only helpers for the published consumer skills.

`SKILL_MARKER` is the single definition of the fixed, path-free comment that every generated
consumer skill carries. The skill generator, the legacy-retirement oracle and the contract tests
all recognise a managed skill by this one constant.
"""

from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
COMMANDS_DIR = ROOT / "templates" / "commands"
CONSUMER_SKILLS = ROOT / "templates" / "consumer-skills"
SOURCE_SKILLS = ROOT / ".github" / "skills"

SKILL_MARKER = "<!-- Generated by DevSpark. Do not edit. -->"
GIT_BASH = Path(r"C:\Program Files\Git\bin\bash.exe")
GENERATOR_SH = "scripts/bash/generate-atomic-shims.sh"
GENERATOR_PS = "scripts/powershell/generate-atomic-shims.ps1"
SOURCE_ONLY_COMMANDS = ("add-application", "discover-constitution", "list-applications", "personalize", "upgrade")
CONSUMER_KEYS = {"name", "description", "user-invocable", "disable-model-invocation"}
GENERATE_TIMEOUT = 240

PLANNING_ID = re.compile(r"\b(?:FR|SC|US|NFR)-\d+\b|\bT\d{3}\b|\bspecs?/\d{3}\b|\.devspark\.work/specs|\b\d{3}-spec-")


def bash_path() -> str | None:
    if GIT_BASH.exists():
        return str(GIT_BASH)
    return shutil.which("bash")


def commands() -> list[str]:
    return sorted(p.stem for p in COMMANDS_DIR.glob("*.md"))


def template_description(command: str, root: Path = ROOT) -> str:
    """Raw text after the first `description:` line of the command template."""
    text = (root / "templates" / "commands" / f"{command}.md").read_bytes().decode("utf-8").replace("\r\n", "\n")
    line = next(line for line in text.split("\n") if line.startswith("description:"))
    return line[len("description:"):].strip(" \t")


def split_skill(text: str) -> tuple[dict, str]:
    match = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text.replace("\r\n", "\n"), re.S)
    assert match, "skill has no frontmatter"
    return yaml.safe_load(match.group(1)), match.group(2)


def consumer_skill(command: str, root: Path = CONSUMER_SKILLS) -> Path:
    return root / f"devspark-{command}" / "SKILL.md"


def resolution_paths(body: str, command: str) -> list[str]:
    """Ordered, de-duplicated override paths a skill body tells the agent to read.

    A path is a backticked `.devspark.work/...` or `.devspark/defaults/...` reference to the
    command's `devspark.<command>.md` file, taken in order of first appearance.
    """
    pattern = re.compile(r"`(\.devspark(?:\.work)?/[^`\s]*devspark\.%s\.md)`" % re.escape(command))
    found: list[str] = []
    for match in pattern.finditer(body):
        if match.group(1) not in found:
            found.append(match.group(1))
    return found


def first_existing(paths: list[str], tree: Path, git_user: str) -> str | None:
    """The path the resolution instruction selects: the first one that exists in `tree`."""
    for path in paths:
        if (tree / path.replace("{git-user}", git_user)).is_file():
            return path
    return None


def expected_resolution(command: str) -> list[str]:
    return [
        f".devspark.work/{{git-user}}/commands/devspark.{command}.md",
        f".devspark.work/commands/devspark.{command}.md",
        f".devspark/defaults/commands/devspark.{command}.md",
    ]


def copy_generation_repo(dest: Path) -> Path:
    """A minimal repository copy the generators can run in: scripts, command templates and
    whichever source inputs the tree currently has."""
    dest.mkdir(parents=True)
    for rel in ("scripts", "templates/commands", ".github/agents", "eng/skills"):
        source = ROOT / rel
        if source.is_dir():
            shutil.copytree(source, dest / rel, ignore=shutil.ignore_patterns("__pycache__"))
    return dest


def run_generator(shell: str, repo: Path, check: bool = False) -> subprocess.CompletedProcess[str]:
    if shell == "bash":
        args = [bash_path(), GENERATOR_SH] + (["--check"] if check else [])
    else:
        args = [shutil.which("pwsh"), "-NoProfile", "-File", GENERATOR_PS] + (["-Check"] if check else [])
    return subprocess.run(
        args, cwd=repo, capture_output=True, text=True, encoding="utf-8", timeout=GENERATE_TIMEOUT
    )


def tree_bytes(base: Path) -> dict[str, bytes]:
    if not base.is_dir():
        return {}
    return {p.relative_to(base).as_posix(): p.read_bytes() for p in sorted(base.rglob("*")) if p.is_file()}
