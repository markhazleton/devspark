"""Contract tests for the source-repository Agent Skills entry points.

Every command template has exactly one generated `.github/skills/devspark-<command>/SKILL.md`.
A skill is a thin entry point: its description is the command template's and its body either routes
directly to `templates/commands/<command>.md` or, for the five source-only commands, is the stop
body kept in `eng/skills/source-stop/<command>.md`. It never carries command instructions or
consults DevSpark command overrides. Both generator twins must produce byte-identical output and
fail their drift check on any divergence.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parent.parent
COMMANDS = ROOT / "templates" / "commands"
SKILLS = ROOT / ".github" / "skills"
SOURCE_STOP_DIR = ROOT / "eng" / "skills" / "source-stop"
GENERATOR_SH = "scripts/bash/generate-atomic-shims.sh"
GENERATOR_PS = "scripts/powershell/generate-atomic-shims.ps1"
GIT_BASH = Path(r"C:\Program Files\Git\bin\bash.exe")
STOP_LINE = "**STOP — This is the DevSpark source repository.**"
SOURCE_STOP_COMMANDS = {"add-application", "discover-constitution", "list-applications", "personalize", "upgrade"}
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
TIMEOUT = 180


def _bash() -> str | None:
    if GIT_BASH.exists():
        return str(GIT_BASH)
    return shutil.which("bash")


GENERATORS = [
    pytest.param("bash", marks=pytest.mark.skipif(_bash() is None, reason="bash not available")),
    pytest.param("pwsh", marks=pytest.mark.skipif(shutil.which("pwsh") is None, reason="pwsh not available")),
]


def _run(shell: str, repo: Path, check: bool = False) -> subprocess.CompletedProcess[str]:
    if shell == "bash":
        args = [_bash(), GENERATOR_SH] + (["--check"] if check else [])
    else:
        args = [shutil.which("pwsh"), "-NoProfile", "-File", GENERATOR_PS] + (["-Check"] if check else [])
    return subprocess.run(args, cwd=repo, capture_output=True, text=True, encoding="utf-8", timeout=TIMEOUT)


def _normalized(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def _template_description(template: Path) -> str:
    """Raw text after the first `description:` line, as the release tooling also reads it."""
    line = next(line for line in _normalized(template).split("\n") if line.startswith("description:"))
    return line[len("description:"):].strip(" \t")


def _routing_body(command: str, stop_dir: Path = SOURCE_STOP_DIR) -> str:
    if command in SOURCE_STOP_COMMANDS:
        return _normalized(stop_dir / f"{command}.md").rstrip("\n")
    return f"Read and follow the instructions in `templates/commands/{command}.md` exactly."


def _expected_skill(command: str, template: Path, stop_dir: Path = SOURCE_STOP_DIR) -> str:
    """The generation contract, stated independently of either generator."""
    description = json.dumps(_template_description(template), ensure_ascii=False)
    sources = (
        f"templates/commands/{command}.md (description) and eng/skills/source-stop/{command}.md (stop). "
        "Do not edit; edit the sources and regenerate."
        if command in SOURCE_STOP_COMMANDS
        else f"templates/commands/{command}.md (description). Do not edit; edit the source and regenerate."
    )
    return (
        "---\n"
        f"name: devspark-{command}\n"
        f"description: {description}\n"
        "user-invocable: true\n"
        "disable-model-invocation: true\n"
        "---\n"
        "\n"
        f"<!-- Generated by scripts/{{bash,powershell}}/generate-atomic-shims from {sources} -->\n"
        "\n"
        f"{_routing_body(command, stop_dir)}\n"
    )


def _split_skill(text: str) -> tuple[dict, str]:
    match = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.S)
    assert match, "skill has no frontmatter"
    return yaml.safe_load(match.group(1)), match.group(2)


def _commands() -> list[str]:
    return sorted(p.stem for p in COMMANDS.glob("*.md"))


# --- Committed skills -------------------------------------------------------------------------


def test_every_command_has_exactly_one_skill_and_no_agent_or_prompt_shims() -> None:
    commands = set(_commands())
    assert len(commands) == 38
    assert {p.name for p in SKILLS.glob("devspark-*") if p.is_dir()} == {f"devspark-{c}" for c in commands}
    assert list((ROOT / ".github" / "agents").glob("devspark.*")) == []
    assert list((ROOT / ".github" / "prompts").glob("devspark.*")) == []
    for command in commands:
        assert [p.name for p in (SKILLS / f"devspark-{command}").iterdir()] == ["SKILL.md"]


@pytest.mark.parametrize("command", _commands())
def test_committed_skill_matches_generation_contract(command: str) -> None:
    skill = SKILLS / f"devspark-{command}" / "SKILL.md"
    expected = _expected_skill(command, COMMANDS / f"{command}.md")
    assert skill.read_bytes() == expected.encode("utf-8")

    frontmatter, _ = _split_skill(expected)
    assert set(frontmatter) == {"name", "description", "user-invocable", "disable-model-invocation"}
    assert frontmatter["name"] == skill.parent.name and NAME_RE.match(frontmatter["name"])
    assert len(frontmatter["name"]) <= 64
    assert 0 < len(frontmatter["description"]) <= 1024
    assert frontmatter["description"] == _template_description(COMMANDS / f"{command}.md")
    assert frontmatter["user-invocable"] is True
    assert frontmatter["disable-model-invocation"] is True


@pytest.mark.parametrize("command", _commands())
def test_skill_is_a_thin_entry_point_without_command_instructions(command: str) -> None:
    _, body = _split_skill((SKILLS / f"devspark-{command}" / "SKILL.md").read_text(encoding="utf-8"))
    routing = body.split("-->\n\n", 1)[1]
    assert routing.rstrip("\n") == _routing_body(command)
    assert len(routing.splitlines()) <= 10
    for command_only in ("## Outline", "## User Input", "{SCRIPT}", "$ARGUMENTS", "handoffs:"):
        assert command_only not in routing
    # The source repository bypasses DevSpark command overrides; skills must not add another precedence.
    for override in (".devspark.work/", "defaults/commands", ".copilot/skills", ".agents/skills"):
        assert override not in routing

    if command in SOURCE_STOP_COMMANDS:
        assert routing.startswith(STOP_LINE + "\n")
    else:
        assert routing == f"Read and follow the instructions in `templates/commands/{command}.md` exactly.\n"


def test_source_stop_variants_are_exactly_the_documented_five() -> None:
    stops = {
        c for c in _commands()
        if _normalized(SKILLS / f"devspark-{c}" / "SKILL.md").split("-->\n\n", 1)[1].startswith(STOP_LINE)
    }
    assert stops == SOURCE_STOP_COMMANDS


@pytest.mark.parametrize("shell", GENERATORS)
def test_repository_has_no_generation_drift(shell: str) -> None:
    result = _run(shell, ROOT, check=True)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "No skill drift detected." in result.stdout


# --- Generator behavior on a fixture repository ----------------------------------------------


def _write(path: Path, text: str, crlf: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))


def _fixture(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    for generator in (GENERATOR_SH, GENERATOR_PS):
        _write(repo / generator, (ROOT / generator).read_text(encoding="utf-8"))
    _write(
        repo / "templates/commands/alpha.md",
        '---\ndescription: Alpha: says "hi" via C:\\tmp — fast.\nscripts:\n  sh: x\n---\n\n## User Input\n\n$ARGUMENTS\n',
    )
    _write(
        repo / "templates/commands/beta.md",
        "<!-- header -->\n\n````markdown\n---\ndescription: Beta wrapped template.\n---\n\nBody\n````\n",
        crlf=True,
    )
    _write(
        repo / "templates/commands/personalize.md",
        "<!-- header -->\n\n````markdown\n---\ndescription: Personalize wrapped template.\n---\n\nBody\n````\n",
        crlf=True,
    )
    _write(
        repo / "eng/skills/source-stop/personalize.md",
        f"{STOP_LINE}\n\nLine one.\n\n---\n\nAfter rule.\n\n\n",
        crlf=True,
    )
    _write(repo / ".devspark.work/commands/devspark.alpha.md", "TEAM-OVERRIDE-SENTINEL\n")
    _write(repo / ".devspark.work/jane-doe/commands/devspark.alpha.md", "DEVELOPER-OVERRIDE-SENTINEL\n")
    return repo


def _generated(repo: Path) -> dict[str, bytes]:
    roots = [repo / ".github/skills", repo / "templates/consumer-skills", repo / "templates/prompts"]
    return {
        p.relative_to(repo).as_posix(): p.read_bytes()
        for root in roots if root.exists() for p in sorted(root.rglob("*")) if p.is_file()
    }


@pytest.mark.skipif(_bash() is None or shutil.which("pwsh") is None, reason="both shells required")
def test_both_generators_produce_identical_contract_output(tmp_path: Path) -> None:
    outputs = {}
    for shell in ("bash", "pwsh"):
        repo = _fixture(tmp_path / shell)
        result = _run(shell, repo)
        assert result.returncode == 0, result.stdout + result.stderr
        outputs[shell] = _generated(repo)
        for command in ("alpha", "beta", "personalize"):
            expected = _expected_skill(command, repo / f"templates/commands/{command}.md", repo / "eng/skills/source-stop")
            assert outputs[shell][f".github/skills/devspark-{command}/SKILL.md"] == expected.encode("utf-8")
    assert outputs["bash"] == outputs["pwsh"]

    alpha, _ = _split_skill(outputs["bash"][".github/skills/devspark-alpha/SKILL.md"].decode("utf-8"))
    assert alpha["description"] == 'Alpha: says "hi" via C:\\tmp — fast.'
    stop = outputs["bash"][".github/skills/devspark-personalize/SKILL.md"].decode("utf-8")
    assert stop.endswith(f"-->\n\n{STOP_LINE}\n\nLine one.\n\n---\n\nAfter rule.\n")
    assert b"\r" not in stop.encode("utf-8")


@pytest.mark.parametrize("shell", GENERATORS)
def test_regeneration_is_idempotent_and_never_reads_or_writes_overrides(shell: str, tmp_path: Path) -> None:
    repo = _fixture(tmp_path)
    overrides = {p: p.read_bytes() for p in (repo / ".devspark.work").rglob("*.md")}

    assert _run(shell, repo).returncode == 0
    first = _generated(repo)
    assert _run(shell, repo).returncode == 0
    assert _generated(repo) == first
    assert _run(shell, repo, check=True).returncode == 0

    assert {p: p.read_bytes() for p in overrides} == overrides
    assert not any(b"SENTINEL" in content for content in first.values())


@pytest.mark.parametrize("shell", GENERATORS)
def test_check_fails_on_changed_missing_and_orphaned_skills(shell: str, tmp_path: Path) -> None:
    repo = _fixture(tmp_path)
    assert _run(shell, repo).returncode == 0
    skill = repo / ".github/skills/devspark-alpha/SKILL.md"
    original = skill.read_bytes()

    skill.write_bytes(original + b"hand edit\n")
    result = _run(shell, repo, check=True)
    assert result.returncode == 1 and "devspark-alpha" in result.stdout
    assert skill.read_bytes() == original + b"hand edit\n", "--check must not write"

    skill.unlink()
    assert _run(shell, repo, check=True).returncode == 1
    assert _run(shell, repo).returncode == 0 and skill.read_bytes() == original

    _write(repo / ".github/skills/other-skill/SKILL.md", "---\nname: other-skill\n---\n")
    assert _run(shell, repo, check=True).returncode == 0, "non-DevSpark skills are not generator-owned"

    orphan = repo / ".github/skills/devspark-ghost/SKILL.md"
    _write(orphan, "unique user content\n")
    result = _run(shell, repo, check=True)
    assert result.returncode == 1 and "devspark-ghost" in result.stdout
    assert _run(shell, repo).returncode == 1
    assert orphan.read_text(encoding="utf-8") == "unique user content\n", "orphans are reported, never deleted"


@pytest.mark.parametrize("shell", GENERATORS)
def test_missing_stop_body_fails_before_any_write(shell: str, tmp_path: Path) -> None:
    repo = _fixture(tmp_path)
    (repo / "eng/skills/source-stop/personalize.md").unlink()
    result = _run(shell, repo)
    assert result.returncode == 2, result.stdout + result.stderr
    assert "personalize" in result.stdout + result.stderr
    assert _generated(repo) == {}


