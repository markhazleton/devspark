"""Regression coverage for DevSpark 7.7.1: OS-independent generated-artifact ordering.

`build_knowledge_index.py` previously sorted `Path` objects directly at several call sites.
`Path`/`PurePath` ordering is platform-flavor-dependent -- `PureWindowsPath` case-normalizes for
comparison, `PurePosixPath` does not -- so a repository containing a case-sensitive ordering
boundary (a root `README.md` next to a nested `README.md` under a differently-cased sibling
directory) produced a different `index.json` node order depending on which OS generated it,
which a cross-platform `--check` then reported as false drift. See `stable_path_sort_key` in
`scripts/build_knowledge_index.py` for the fix.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path, PurePosixPath, PureWindowsPath

ROOT = Path(__file__).resolve().parent.parent
ENGINE = ROOT / "scripts" / "build_knowledge_index.py"
FIXED_TIME = "2026-01-01T00:00:00Z"

sys.path.insert(0, str(ROOT / "scripts"))
from build_knowledge_index import stable_path_sort_key  # noqa: E402


def test_stable_path_sort_key_agrees_across_platform_flavors() -> None:
    """Windows-flavored and POSIX-flavored paths must produce identical canonical ordering.

    This is the boundary that broke: a case-sensitive comparison of the raw path segments
    ("README.md" < "intent_catalog/README.md" only under a case-sensitive/POSIX-style compare)
    versus a case-normalizing one (Windows path comparison folds case first).
    """
    expected = [
        ".knowledge/reference/README.md",
        ".knowledge/reference/intent_catalog/README.md",
    ]

    windows_paths = [
        PureWindowsPath(".knowledge/reference/intent_catalog/README.md"),
        PureWindowsPath(".knowledge/reference/README.md"),
    ]
    posix_paths = [
        PurePosixPath(".knowledge/reference/intent_catalog/README.md"),
        PurePosixPath(".knowledge/reference/README.md"),
    ]

    windows_ordered = [p.as_posix() for p in sorted(windows_paths, key=stable_path_sort_key)]
    posix_ordered = [p.as_posix() for p in sorted(posix_paths, key=stable_path_sort_key)]

    assert windows_ordered == expected
    assert posix_ordered == expected


def test_stable_path_sort_key_is_case_sensitive_not_lowercased() -> None:
    """The key must not fold case -- only normalize the OS-comparison semantics away."""
    assert stable_path_sort_key(Path("B.md")) != stable_path_sort_key(Path("b.md"))
    ordered = sorted([Path("b.md"), Path("A.md")], key=stable_path_sort_key)
    # Plain codepoint order: uppercase 'A' (0x41) sorts before lowercase 'b' (0x62) on every OS.
    assert [p.name for p in ordered] == ["A.md", "b.md"]


def _write_case_boundary_fixture(repo: Path) -> None:
    """Build the generalized regression fixture: root README, nested README, a case-sensitive
    ordering boundary, reproducible under either path flavor. Mirrors the production failure
    pattern without hard-coding any Triage-specific domain content.
    """
    root_readme = repo / ".knowledge" / "reference" / "README.md"
    nested_readme = repo / ".knowledge" / "reference" / "intent_catalog" / "README.md"
    root_readme.parent.mkdir(parents=True, exist_ok=True)
    nested_readme.parent.mkdir(parents=True, exist_ok=True)
    root_readme.write_text("# Reference\n\nCurrent reference root.\n", encoding="utf-8")
    nested_readme.write_text("# Intent catalog\n\nCurrent intent catalog reference.\n", encoding="utf-8")


def _run(repo: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(ENGINE), "--repo-root", str(repo), "--stdout", "--generated-at", FIXED_TIME],
        text=True,
        capture_output=True,
    )


def test_generated_index_orders_case_boundary_fixture_deterministically(tmp_path: Path) -> None:
    """Integration-level: exercise the real generator, not just the helper in isolation."""
    _write_case_boundary_fixture(tmp_path)

    result = _run(tmp_path)
    assert result.returncode == 0, result.stderr
    index = json.loads(result.stdout)

    reference_nodes = [node["path"] for node in index["nodes"] if node["path"].startswith(".knowledge/reference/")]
    assert reference_nodes == [
        ".knowledge/reference/README.md",
        ".knowledge/reference/intent_catalog/README.md",
    ]


def test_repeated_generation_is_byte_identical(tmp_path: Path) -> None:
    """Same repository state + same DevSpark version must equal same generated bytes."""
    _write_case_boundary_fixture(tmp_path)

    first = _run(tmp_path)
    second = _run(tmp_path)
    assert first.returncode == 0, first.stderr
    assert second.returncode == 0, second.stderr
    assert first.stdout == second.stdout


def test_coverage_report_is_deterministic_for_case_boundary_fixture(tmp_path: Path) -> None:
    """Coverage is derived from `index["entities"]`, which carries no filesystem-path-ordered
    content in this fixture (no `.knowledge/entities/` present) -- demonstrated rather than
    assumed, per the requirement to prove which artifacts are actually affected.
    """
    _write_case_boundary_fixture(tmp_path)

    coverage_a = tmp_path / "coverage-a.json"
    coverage_b = tmp_path / "coverage-b.json"
    index_out = tmp_path / "index.json"
    run_a = subprocess.run(
        [
            sys.executable,
            str(ENGINE),
            "--repo-root",
            str(tmp_path),
            "--output",
            str(index_out),
            "--coverage-output",
            str(coverage_a),
            "--generated-at",
            FIXED_TIME,
        ],
        text=True,
        capture_output=True,
    )
    run_b = subprocess.run(
        [
            sys.executable,
            str(ENGINE),
            "--repo-root",
            str(tmp_path),
            "--output",
            str(index_out),
            "--coverage-output",
            str(coverage_b),
            "--generated-at",
            FIXED_TIME,
        ],
        text=True,
        capture_output=True,
    )
    assert run_a.returncode == 0, run_a.stderr
    assert run_b.returncode == 0, run_b.stderr
    assert coverage_a.read_text(encoding="utf-8") == coverage_b.read_text(encoding="utf-8")
